    horizons_avail = df_metrics['Horizon'].unique().tolist()
    selected_horizon = st.sidebar.selectbox("Pilih Horizon Prediksi", horizons_avail, index=min(1, len(horizons_avail)-1))
    models_avail = df_metrics['Model'].unique().tolist()
    selected_models = st.sidebar.multiselect("Filter Model Perbandingan", models_avail, default=models_avail)

